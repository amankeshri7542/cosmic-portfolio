import assert from "node:assert/strict";
import fs from "node:fs";
import { createHash, randomBytes } from "node:crypto";
import { sql } from "@vercel/postgres";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const origin = process.env.PORTFOLIO_URL || "http://127.0.0.1:3000";
const password = fs.readFileSync(".env.editor-access", "utf8").match(/^Password: (.+)$/m)[1];
const slug = `qa-editor-${Date.now()}`;
const browser = await chromium.launch({channel:"chrome",headless:true});
let checks = 0, token;
const check = (name, ok) => { assert.ok(ok, name); checks++; };
const context = await browser.newContext();
const api = context.request;
const post = (path, data, headers = {}) => api.post(origin + path, {data,headers:{Origin:origin,...headers}});
let draft = {slug,title:"QA publishing check",excerpt:"An isolated verification article, removed after the check.",content:"## Public first version\n\nThis body verifies Markdown publishing.\n\n<script>window.markdownExecuted=true</script>\n\n[unsafe](javascript:alert(1))",cover:"",coverAlt:"",sample:false,version:0};
try {
  check("anonymous reads denied", (await api.get(origin+"/api/editor/posts")).status() === 401);
  check("anonymous writes denied", (await post("/api/editor/posts",{...draft,intent:"save"})).status() === 401);
  check("cross-origin login denied", (await post("/api/editor/session",{password},{Origin:"https://example.com"})).status() === 403);
  const page = await context.newPage();
  await page.goto(origin+"/write");
  check("editor noindex", (await page.locator('meta[name="robots"]').getAttribute("content")).includes("noindex"));
  await page.getByLabel("Editor password").fill(password);
  await page.getByRole("button",{name:"Open the writer’s desk"}).click();
  await page.getByRole("button",{name:"New article"}).waitFor();
  const cookie = (await context.cookies()).find(c=>c.name==="portfolio_editor");
  check("session cookie protected", cookie?.httpOnly && cookie.sameSite === "Strict" && (!origin.startsWith("https:") || cookie.secure));
  token = cookie.value;
  check("authenticated posts available", (await api.get(origin+"/api/editor/posts")).status() === 200);
  check("cross-origin write denied", (await post("/api/editor/posts",{...draft,intent:"save"},{Origin:"https://example.com"})).status() === 403);
  check("invalid slug rejected", (await post("/api/editor/posts",{...draft,slug:"../secret",intent:"save"})).status() === 400);
  check("unsafe cover rejected", (await post("/api/editor/posts",{...draft,cover:"javascript:alert(1)",coverAlt:"test",intent:"save"})).status() === 400);
  check("oversize body rejected", (await post("/api/editor/posts",{...draft,content:"x".repeat(210000),intent:"save"})).status() === 413);
  await page.locator('input[type="file"]').setInputFiles({name:"note.md",mimeType:"text/markdown",buffer:Buffer.from("# Imported title\n\nA paragraph written in Markdown.")});
  await page.waitForFunction(()=>document.querySelector("#post-title").value==="Imported title");
  check("Markdown import populates title and body",(await page.locator("#post-content").inputValue()).includes("A paragraph written in Markdown."));
  await page.getByLabel("Title",{exact:true}).fill(draft.title);
  await page.getByLabel("Article URL",{exact:false}).fill(slug);
  await page.getByLabel("Short description").fill(draft.excerpt);
  await page.locator("#post-content").fill(draft.content);
  await page.getByRole("button",{name:"Save draft",exact:true}).click();
  await page.getByRole("status").filter({hasText:"Draft saved"}).waitFor();
  draft.version = 1;
  check("draft private", (await api.get(origin+"/blogs/"+slug)).status() === 404);
  check("draft absent sitemap", !(await (await api.get(origin+"/sitemap.xml")).text()).includes(slug));
  check("duplicate slug rejected", (await post("/api/editor/posts",{...draft,version:0,intent:"save"})).status() === 409);
  for (const width of [320,390,760,943,1440]) {
    await page.setViewportSize({width,height:844});
    check(`writer fits ${width}`,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  }
  await page.getByRole("button",{name:"Preview article"}).click();
  check("safe preview",await page.locator(".writer-preview script").count()===0 && await page.locator('.writer-preview a[href^="javascript:"]').count()===0);
  fs.mkdirSync("docs/qa/publishing",{recursive:true});
  await page.evaluate(()=>{document.activeElement?.blur();scrollTo({top:0,behavior:"instant"});});
  await page.screenshot({path:"docs/qa/publishing/editor-desktop.png",fullPage:true});
  await page.setViewportSize({width:390,height:844});
  check("preview fits mobile",await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.evaluate(()=>{document.activeElement?.blur();scrollTo({top:0,behavior:"instant"});});
  await page.screenshot({path:"docs/qa/publishing/editor-mobile.png",fullPage:true});
  await page.getByRole("button",{name:"Publish article",exact:true}).click();
  await page.getByRole("status").filter({hasText:"Published."}).waitFor();
  let stored = (await (await api.get(origin+"/api/editor/posts")).json()).posts.find(p=>p.slug===slug);
  draft.version=stored.version;
  const firstDate = stored.published.dateISO;
  check("published on index", (await (await api.get(origin+"/blogs")).text()).includes(slug));
  check("published on homepage", (await (await api.get(origin)).text()).includes(slug));
  check("published in sitemap", (await (await api.get(origin+"/sitemap.xml")).text()).includes(slug));
  await page.goto(origin+"/blogs/"+slug);
  check("canonical correct",await page.locator('link[rel="canonical"]').getAttribute("href")===`https://www.amankeshri.com/blogs/${slug}`);
  check("article structured data",(await page.locator('script[type="application/ld+json"]').allTextContents()).some(s=>JSON.parse(s)["@graph"]?.some(x=>x["@type"]==="BlogPosting" && x.datePublished===firstDate)));
  check("raw HTML ignored",!await page.evaluate(()=>window.markdownExecuted) && await page.locator('.article-body a[href^="javascript:"]').count()===0);
  check("social image renders",(await api.get(origin+`/blogs/${slug}/opengraph-image`)).status()===200);
  let response=await post("/api/editor/posts",{...draft,content:"## Private revision\n\nThis updated content must stay private until republished.",intent:"save"});
  check("revision saved",response.status()===200);
  stored=(await response.json()).post; draft={...stored.draft,version:stored.version};
  await page.reload();
  check("saved revision remains private",(await page.locator(".article-body").innerText()).includes("Public first version"));
  check("stale version rejected",(await post("/api/editor/posts",{...draft,version:1,intent:"publish"})).status()===409);
  response=await post("/api/editor/posts",{...draft,intent:"publish"}); stored=(await response.json()).post;
  check("publication date preserved",stored.published.dateISO===firstDate && stored.published.modifiedISO>=firstDate);
  await page.reload();check("revision published",(await page.locator(".article-body").innerText()).includes("Private revision"));
  response=await post("/api/editor/posts",{...stored.draft,version:stored.version,intent:"unpublish"});
  check("unpublish retains draft",(await response.json()).post.published===null);
  check("unpublished article gone",(await api.get(origin+"/blogs/"+slug)).status()===404);
  check("unpublished absent sitemap",!(await (await api.get(origin+"/sitemap.xml")).text()).includes(slug));
  await page.goto(origin+"/blogs/one-sale-three-records");
  check("samples noindex",(await page.locator('meta[name="robots"]').getAttribute("content")).includes("noindex"));
  check("samples absent sitemap",!(await (await api.get(origin+"/sitemap.xml")).text()).includes("one-sale-three-records"));
  check("logout succeeds",(await api.delete(origin+"/api/editor/session",{headers:{Origin:origin}})).status()===200);
  check("revoked session rejected",(await api.get(origin+"/api/editor/posts",{headers:{Cookie:`portfolio_editor=${token}`}})).status()===401);
  check("forged session rejected",(await api.get(origin+"/api/editor/posts",{headers:{Cookie:`portfolio_editor=${randomBytes(32).toString("hex")}`}})).status()===401);
  await sql`INSERT INTO portfolio_editor_sessions (token_hash,expires_at) VALUES (${createHash("sha256").update(token).digest("hex")},now()-interval '1 minute')`;
  check("expired session rejected",(await api.get(origin+"/api/editor/posts",{headers:{Cookie:`portfolio_editor=${token}`}})).status()===401);
  console.log(JSON.stringify({passed:checks}));
} finally {
  await sql`DELETE FROM portfolio_posts WHERE slug=${slug}`;
  if(token) await sql`DELETE FROM portfolio_editor_sessions WHERE token_hash=${createHash("sha256").update(token).digest("hex")}`;
  await sql.end(); await browser.close();
}
