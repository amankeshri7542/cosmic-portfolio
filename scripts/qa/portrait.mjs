import { chromium, devices } from "@playwright/test";
const out = process.argv[2] ?? ".qa";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto("http://127.0.0.1:3001/about", { waitUntil: "domcontentloaded" });
await p.waitForTimeout(1100);
const fig = p.locator("figure[data-size]").first();
await fig.screenshot({ path: `${out}/portrait-building.jpg`, type: "jpeg", quality: 82 });
await p.waitForTimeout(2600);
await fig.screenshot({ path: `${out}/portrait-built.jpg`, type: "jpeg", quality: 82 });
const box = await fig.locator("a").filter({ hasText: "PostgreSQL" }).boundingBox();
await p.mouse.move(box.x + box.width / 2, box.y + box.height / 2, { steps: 12 });
await p.waitForTimeout(900);
await fig.screenshot({ path: `${out}/portrait-hover.jpg`, type: "jpeg", quality: 82 });
await p.screenshot({ path: `${out}/about-top.jpg`, type: "jpeg", quality: 78 });
const m = await b.newPage({ ...devices["Pixel 7"] });
await m.goto("http://127.0.0.1:3001/about", { waitUntil: "networkidle" });
await m.waitForTimeout(3200);
await m.screenshot({ path: `${out}/about-mobile.jpg`, type: "jpeg", quality: 75 });
console.log("overflow", await m.evaluate(() => document.documentElement.scrollWidth - innerWidth));
await b.close();
