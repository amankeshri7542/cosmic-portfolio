import { chromium, devices } from "@playwright/test";
const out = process.argv[2] ?? ".qa";
const b = await chromium.launch();
const p = await b.newPage({ ...devices["Pixel 7"] });
await p.goto("http://127.0.0.1:3001/", { waitUntil: "networkidle" });
await p.waitForTimeout(1000);
const panel = async (id) => {
  await p.locator(`#${id} [role=group]`).scrollIntoViewIfNeeded();
  await p.evaluate((id) => { const el = document.querySelector(`#${id} [role=group]`); window.scrollTo(0, el.getBoundingClientRect().top + scrollY - innerHeight * 0.55); }, id);
  await p.waitForTimeout(1200);
};
await panel("interface");
await p.locator("#interface").getByRole("button", { name: /TMT Bar/ }).tap();
await p.screenshot({ path: `${out}/mp-1.jpg`, type: "jpeg", quality: 75 });
await panel("data");
await p.locator("#data").getByRole("switch", { name: "Without a transaction" }).tap();
await p.locator("#data").getByRole("switch", { name: "Cut the power mid-write" }).tap();
await p.locator("#data").getByRole("button", { name: "Commit the sale" }).tap();
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/mp-2.jpg`, type: "jpeg", quality: 75 });
await panel("ship");
await p.locator("#ship").getByRole("button", { name: "Push to main" }).tap();
await p.waitForTimeout(3500);
await p.screenshot({ path: `${out}/mp-3.jpg`, type: "jpeg", quality: 75 });
await p.evaluate(() => document.getElementById("receipt").scrollIntoView());
await p.waitForTimeout(2200);
await p.screenshot({ path: `${out}/mp-4.jpg`, type: "jpeg", quality: 75 });
console.log("overflow:", await p.evaluate(() => document.documentElement.scrollWidth - innerWidth));
await b.close();
